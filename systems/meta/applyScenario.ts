import type { PlayerStats } from '../../types/player';
import type { Track } from '../../types/music';
import { usePlayerStore } from '../../store/playerStore';
import { useGameStore } from '../../store/gameStore';
import { useCareerStore } from '../../store/careerStore';
import { useMusicStore } from '../../store/musicStore';
import { usePeopleStore } from '../../store/peopleStore';
import { useIdentityStore } from '../../store/identityStore';
import { useLegalStore } from '../../store/legalStore';
import { getScenario } from '../../data/meta/scenarios';
import { makeSeed } from '../identity/seedEngine';
import { grantTrait } from '../identity/traits';

/**
 * Starting scenarios, applied at onboarding in two halves: `applyScenario`
 * right after the player is created (money, fans, stats, tags, traits, a past
 * hit, seeds), and `finishScenario` after the first week exists (the family
 * is generated by then, and the scenario's first line opens the Deck).
 */

export const FAMOUS_PARENT_TRAIT = 'famous-parent';

export function applyScenario(id: string): void {
  const def = getScenario(id);
  const ps = usePlayerStore.getState();
  const player = ps.player;
  if (!def || !player) return;
  useIdentityStore.getState().setScenario(id);
  if (def.id === 'classic') return;

  if (def.money !== undefined) ps.addMoney(def.money - player.money);
  const changes: { stat: keyof PlayerStats; delta: number }[] = Object.entries(def.stats ?? {}).map(
    ([stat, delta]) => ({ stat: stat as keyof PlayerStats, delta: delta as number })
  );
  if (def.fans) changes.push({ stat: 'fans', delta: def.fans });
  if (changes.length > 0) ps.updateStats(changes);

  const game = useGameStore.getState();
  for (const tag of def.tags ?? []) game.addTag(tag);
  for (const trait of def.traits ?? []) grantTrait(trait);
  if (def.mental) useCareerStore.getState().adjustMental(def.mental);

  if (def.pastHit) {
    const h = def.pastHit;
    const track: Track = {
      id: `track-past-${player.createdAt}`,
      title: h.title,
      type: 'single',
      genre: player.genre,
      releasedAtWeek: 1 - h.weeksAgo,
      quality: 74,
      replayValue: 80,
      originality: 62,
      mainstreamAppeal: 85,
      peakChartPosition: h.peak,
      peakFans: player.stats.fans,
      weeklyStreams: h.weeklyStreams,
      totalStreams: h.totalStreams,
      // A song that outlived its moment: it streams steadily, untouched by the weekly curve.
      status: 'classic',
      wentViral: h.viral,
      criticsScore: 70,
      owner: h.labelOwned ? 'label' : 'artist',
      ownerLabelId: h.labelOwned ? 'goldline' : undefined,
      royaltyShare: h.labelOwned ? 0.15 : 0.85,
    };
    useMusicStore.getState().addTrack(track);
  }

  for (const plant of def.seeds ?? []) {
    useIdentityStore.getState().addSeed(makeSeed(plant, 1));
  }

  if (def.traits?.includes('jailbird')) {
    useLegalStore.getState().addRecord({
      chargeId: 'weapons',
      label: 'Weapons possession',
      week: 1,
      outcome: 'served',
      weeks: 24,
    });
  }
}

/** After the first week is built: the family's famous parent, and the opening line. */
export function finishScenario(): void {
  const id = useIdentityStore.getState().scenarioId;
  const def = id ? getScenario(id) : undefined;
  const player = usePlayerStore.getState().player;
  if (!def || !player) return;

  if (def.famousParent) {
    const people = usePeopleStore.getState();
    const parent = people.people.find((p) => p.role === 'parent');
    if (parent) {
      people.setPeople(
        people.people.map((p) =>
          p.id === parent.id
            ? {
                ...p,
                traits: [...new Set([...p.traits, FAMOUS_PARENT_TRAIT, 'funds-you'])],
                allowance: Math.max(p.allowance ?? 0, 2_000),
                affinity: Math.max(p.affinity, 40),
              }
            : p
        )
      );
    }
  }
  useGameStore.getState().addStoryLine(def.intro.replace(/\{artist\}/g, player.artistName), 'personal', 'scenario');
}
