def reaction_specs(rng: random.Random, n: int = 70) -> list:
    specs = []
    for i in range(n):
        rid, desc = REACTIONS[i % len(REACTIONS)]
        gender = 'woman' if (i // len(REACTIONS) + i) % 2 == 0 else 'man'
        who, group, age = who_for(rng, gender)
        place = rng.choice(['at home on a couch', 'in a bedroom', 'in a kitchen', 'in a car', 'at an office desk', 'in a living room'])
        prompt = f'close-up candid photo of {who}, {desc}, {place}, exaggerated reaction, meme-worthy, {REAL}'
        specs.append({
            'key': f'r{i:03d}',
            'category': 'reaction',
            'reaction': rid,
            'gender': gender,
            'age': age_band(age),
            'origin': group,
            'prompt': prompt,
            'size': [1024, 1024],
        })
    return specs


