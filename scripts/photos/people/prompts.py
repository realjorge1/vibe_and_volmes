def build() -> list:
    rng = random.Random(20261001)
    specs = []
    specs += selfie_specs(rng, 220, 0, admirer=False)
    specs += selfie_specs(rng, 80, 0, admirer=True)
    specs += scene_specs(rng)
    specs += reaction_specs(rng, 70)
    specs += rival_specs()
    for s in specs:
        s.setdefault('seed', rng.randrange(1, 2**31 - 1))
        s['negative'] = NEGATIVE
    return specs


