def who_for(rng: random.Random, gender: str) -> tuple:
    origin, group = rng.choice(ORIGINS)
    age = rng.choice([21, 22, 23, 24, 25, 26, 27, 28, 30, 33])
    return f'a {age} year old {origin_label(origin, gender)} {gender}', group, age


def scene_specs(rng: random.Random) -> list:
    specs = []
    n = 0
    for scene_id, tags, count, tpl in SCENES:
        for i in range(count):
            gender = 'woman' if (i + n) % 2 == 0 else 'man'
            if scene_id == 'girls-night':
                gender = 'woman'
            if scene_id == 'boys-night':
                gender = 'man'
            who, group, age = who_for(rng, gender)
            anon = f'({gender})'
            prompt = tpl.format(who=who, anon=anon, place=rng.choice(PLACES)) + f', {REAL}'
            landscape = scene_id in ('concert-phones', 'stage-back', 'charity-event', 'red-carpet-back', 'late-food')
            specs.append({
                'key': f's{len(specs):03d}',
                'category': 'scene',
                'scene': scene_id,
                'tags': tags,
                'gender': gender,
                'age': age_band(age),
                'origin': group,
                'prompt': prompt,
                'size': [1216, 832] if landscape else [832, 1216],
                'faceless': 'player' in tags,
            })
        n += count
    return specs


