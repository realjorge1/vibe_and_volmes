"""Build the bundled social-media photo pack.

Every photo is CC0 (public domain) from StockSnap, found through the Openverse
API and hand-picked for the phone apps: stages, crowds, studios, cars, cities,
pets and the rest of a music star's feed. Faces are avoided on purpose, so the
fictional artist and the people posting about them stay faceless.

    py scripts/photos/build-photo-pack.py [--cache DIR] [--quality 60] [--rebuild]

Reads scripts/photos/photo-picks.json and writes:
  assets/photos/<id>.webp         resized, WebP
  data/photos/photoPack.ts        the typed manifest the app imports
  assets/photos/CREDITS.md        provenance for every file

Needs Pillow (`py -m pip install pillow`).
"""
import argparse, json, os, urllib.request
from PIL import Image, ImageFilter, ImageStat

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36'
MAXW_PORTRAIT, MAXW_LAND = 864, 960


def source(pid, cache):
    path = os.path.join(cache, f'{pid}.jpg')
    if not (os.path.exists(path) and os.path.getsize(path) > 10_000):
        url = f'https://cdn.stocksnap.io/img-thumbs/960w/{pid}.jpg'
        req = urllib.request.Request(url, headers={'User-Agent': UA, 'Referer': 'https://stocksnap.io/'})
        with urllib.request.urlopen(req, timeout=60) as r:
            open(path, 'wb').write(r.read())
    return path


def focus_of(im):
    """Centroid of edge energy, pulled toward the middle: where cover crops aim."""
    w, h = im.size
    g = im.convert('L').resize((48, max(1, round(48 * h / w))))
    e = g.filter(ImageFilter.FIND_EDGES)
    px = e.load()
    gw, gh = e.size
    sx = sy = tot = 0.0
    for y in range(1, gh - 1):
        for x in range(1, gw - 1):
            v = px[x, y] ** 1.5
            sx += v * x
            sy += v * y
            tot += v
    fx = sx / tot / gw if tot else 0.5
    fy = sy / tot / gh if tot else 0.5
    return round(0.5 + (fx - 0.5) * 0.7, 3), round(0.5 + (fy - 0.5) * 0.7, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cache', default=os.path.join(ROOT, '.photo-cache'))
    ap.add_argument('--quality', type=int, default=60)
    ap.add_argument('--rebuild', action='store_true', help='re-download and re-encode photos already built')
    args = ap.parse_args()
    os.makedirs(args.cache, exist_ok=True)
    out_dir = os.path.join(ROOT, 'assets', 'photos')
    os.makedirs(out_dir, exist_ok=True)

    picks = json.load(open(os.path.join(ROOT, 'scripts', 'photos', 'photo-picks.json'), encoding='utf-8'))
    rows, credits, total = [], [], 0
    for p in picks:
        pid = p['id']
        key = pid.lower()
        path = os.path.join(out_dir, f'{key}.webp')
        cached = os.path.join(args.cache, f'{pid}.jpg')
        if os.path.exists(path) and not (os.path.exists(cached) and os.path.getsize(cached) > 10_000) and not args.rebuild:
            # Built before and the original isn't cached: keep the file (no re-download).
            im = Image.open(path).convert('RGB')
        else:
            im = Image.open(source(pid, args.cache)).convert('RGB')
            w, h = im.size
            maxw = MAXW_PORTRAIT if h > w else MAXW_LAND
            if w > maxw:
                im = im.resize((maxw, round(h * maxw / w)), Image.LANCZOS)
            im.save(path, 'WEBP', quality=args.quality, method=6)
        w, h = im.size
        fx, fy = focus_of(im)
        mean = ImageStat.Stat(im.resize((16, 16))).mean
        tint = '#%02X%02X%02X' % tuple(int(v) for v in mean[:3])
        lum = 0.2126 * mean[0] + 0.7152 * mean[1] + 0.0722 * mean[2]
        total += os.path.getsize(path)
        tags = ', '.join(f"'{t}'" for t in p['tags'])
        rows.append(
            f"  {{ key: '{key}', src: require('../../assets/photos/{key}.webp'), w: {w}, h: {h}, "
            f"tags: [{tags}], focus: [{fx}, {fy}], tint: '{tint}', dark: {'true' if lum < 90 else 'false'} }},"
        )
        credits.append(f"| `{key}.webp` | {p['title'] or ''} | {p['creator'] or ''} | [StockSnap]({p['landing']}) | CC0 |")

    all_tags = sorted({t for p in picks for t in p['tags']})
    ts = [
        '/* eslint-disable */',
        '// GENERATED by scripts/media/build-photo-pack.py from photo-picks.json. Do not edit by hand.',
        '',
        '/** What a photo shows. A photo can carry several; the first is its main scene. */',
        'export type PhotoTag =',
        *[f"  | '{t}'" for t in all_tags],
        '  ;',
        '',
        'export interface StockPhoto {',
        '  key: string;',
        '  /** Bundled asset (require), or a file on the phone (a photo the player posted). */',
        '  src: number | { uri: string };',
        '  w: number;',
        '  h: number;',
        '  tags: readonly PhotoTag[];',
        '  /** Where the subject sits, 0..1 from the top-left: cover crops aim here. */',
        '  focus: readonly [number, number];',
        '  /** Average color: the placeholder while it decodes. */',
        '  tint: string;',
        '  /** Dark overall: white text reads on it. */',
        '  dark: boolean;',
        '}',
        '',
        f'/** {len(picks)} CC0 photos (StockSnap via Openverse). Credits: assets/photos/CREDITS.md. */',
        'export const PHOTOS: readonly StockPhoto[] = [',
        *rows,
        '];',
        '',
    ]
    open(os.path.join(ROOT, 'data', 'photos', 'photoPack.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(ts))
    md = [
        '# Photo credits',
        '',
        'Every photo in this folder is released under **CC0 1.0** (public domain dedication) on',
        '[StockSnap](https://stocksnap.io), found through the [Openverse](https://openverse.org) API.',
        'No attribution is required; it is listed here for provenance. Rebuild with',
        '`py scripts/photos/build-photo-pack.py`.',
        '',
        '| File | Title | Photographer | Source | License |',
        '| --- | --- | --- | --- | --- |',
        *credits,
        '',
    ]
    open(os.path.join(ROOT, 'assets', 'photos', 'CREDITS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(md))
    print(f'{len(picks)} photos, {total / 1048576:.1f} MB')


if __name__ == '__main__':
    main()
